function writeInterfacePlots(runDir,cfg,alignment)
%WRITEINTERFACEPLOTS Generate the eight required layer-by-layer traces.
plotDir = fullfile(runDir,"plots");
if ~isfolder(plotDir), mkdir(plotDir); end
trace = readtable(fullfile(runDir,"packet_trace.csv"));
att = readtable(fullfile(runDir,"internal_ATT.csv"));
rcin = readtable(fullfile(runDir,"internal_RCIN.csv"));
rcout = readtable(fullfile(runDir,"internal_RCOU.csv"));
sim = readtable(fullfile(runDir,"simulation_data.csv"));
feedback = readtable(fullfile(runDir,"feedback_trace.csv"));
ap = @(x) double(x.ap_time_s)-alignment;

savePlot("01_rc_command_trace",trace.sim_time_s, ...
    [trace.rc_roll_normalized,trace.rc1_sent_us], ...
    ["RC roll normalized","RC1 sent (us)"],"Test runner and bridge RC command");
savePlot("02_rc_received_by_ardupilot",ap(rcin),rcin.C1, ...
    "ArduPilot RCIN.C1 (us)","RC received by ArduPilot");
savePlot("03_fbwa_internal_target",ap(att), ...
    [att.DesRoll,att.Roll],["ATT.DesRoll","ATT.Roll"], ...
    "ArduPilot FBWA internal target");
savePlot("04_servo_output_trace",ap(rcout), ...
    [rcout.C1,rcout.C2,rcout.C3,rcout.C4,rcout.C5], ...
    ["RCOU.C1","RCOU.C2","RCOU.C3","RCOU.C4","RCOU.C5"], ...
    "ArduPilot servo outputs (PWM us)");
savePlot("05_protocol_actuator_trace",trace.sim_time_s, ...
    [trace.protocol_aileron_left_pwm_us,trace.protocol_aileron_right_pwm_us, ...
    trace.protocol_elevator_pwm_us,trace.protocol_rudder_pwm_us], ...
    ["left","right","elevator","rudder"], ...
    "JSON servo packet received by bridge (PWM us)");
savePlot("06_surface_angle_trace",sim.time_s, ...
    [sim.aileron_left_actual_deg,sim.aileron_right_actual_deg, ...
    sim.elevator_actual_deg,sim.rudder_actual_deg], ...
    ["left aileron","right aileron","elevator","rudder"], ...
    "Physical actuator-model surface state (deg)");
savePlot("07_truth_feedback_trace",feedback.sim_time_s, ...
    [rad2deg(feedback.roll_rad),rad2deg(feedback.pitch_rad), ...
    rad2deg(feedback.yaw_rad)], ["JSON roll","JSON pitch","JSON yaw"], ...
    "Truth feedback sent to JSON backend (deg)");
savePlot("08_timing_trace",trace.sim_time_s, ...
    [trace.packet_interval_ms,trace.round_trip_ms], ...
    ["packet interval ms","round trip ms"],"Lock-step timing trace");

controlDir = fullfile(plotDir,"control_baseline");
if ~isfolder(controlDir), mkdir(controlDir); end
f = figure("Visible","off","Color","w");
plot(ap(att),att.DesRoll,"LineWidth",1.3); hold on;
plot(ap(att),att.Roll,"LineWidth",1.3); grid on;
xlabel("Simulation time (s)"); ylabel("Roll (deg)");
legend("ArduPilot desired","actual","Location","best");
title("Control baseline — "+string(cfg.scenario.name),"Interpreter","none");
exportgraphics(f,fullfile(controlDir,"roll_tracking.png"),"Resolution",160); close(f);

    function savePlot(name,x,y,labels,titleText)
        f = figure("Visible","off","Color","w");
        plot(double(x),double(y),"LineWidth",1.1); grid on;
        xlabel("Simulation time (s)"); legend(labels,"Location","best");
        title(titleText,"Interpreter","none");
        exportgraphics(f,fullfile(plotDir,name+".png"),"Resolution",160);
        close(f);
    end
end
