function value = pitchAnswer(T)
parts = strings(height(T),1);
for k=1:height(T)
    parts(k) = sprintf("%.0f m/s: T %s, q_avg %s, q_op_max %.2f (%s)", ...
        T.Airspeed_mps(k),numberOrBlank(T.Time_s(k)), ...
        numberOrBlank(T.q_avg_deg_s(k)),T.q_op_max_deg_s(k),T.Limit(k));
end
value = join(parts,"; ");
end

function value = pitchBoundaryAnswer(runs)
if isempty(runs)
    value = "No formal Pitch run is available for boundary analysis.";
    return
end
pitchRuns = runs(runs.Axis=="pitch",:);
n = height(pitchRuns);
dCount = 0;
pCount = 0;
effective = nan(n,1);
rejected = nan(n,1);
parsed = 0;
for k=1:n
    parseFile = fullfile(pitchRuns.RunDirectory(k),"AUTOTUNE_PARSE_SUMMARY.json");
    if ~isfile(parseFile), continue; end
    info = jsondecode(fileread(parseFile));
    parsed = parsed + 1;
    dCount = dCount + double(info.d_boundary_observed);
    pCount = pCount + double(info.p_boundary_observed);
    effective(k) = double(info.effective_excitation_count);
    rejected(k) = double(info.rejected_excitation_count);
end
if parsed == 0
    value = "No Pitch parser summaries are available; no root cause is signed off.";
elseif all(effective(isfinite(effective))==effective(find(isfinite(effective),1))) && ...
        all(rejected(isfinite(rejected))==rejected(find(isfinite(rejected),1)))
    value = sprintf("Current observation, not a proven single root cause: %d/%d Pitch runs " + ...
        "observed the D boundary and %d/%d observed the P boundary; each parsed run had " + ...
        "%d effective and %d rejected excitations. The prior multi-fold Pitch FF spread " + ...
        "remains inconclusive because no official Pitch final parameter set exists.", ...
        dCount,parsed,pCount,parsed,effective(find(isfinite(effective),1)), ...
        rejected(find(isfinite(rejected),1)));
else
    value = sprintf("Current observation, not a proven single root cause: %d/%d Pitch runs " + ...
        "observed the D boundary and %d/%d observed the P boundary. The prior multi-fold " + ...
        "Pitch FF spread remains inconclusive because no official Pitch final parameter set exists.", ...
        dCount,parsed,pCount,parsed);
end
end

function value = recommendation(repeatPass)
if repeatPass
    value = "Level 2 is the balanced **model-validation candidate**. Level 1 is the conservative candidate and Level 3 the more aggressive engineering candidate. None is a flight-release recommendation until hardware direction/travel verification and flight-test acceptance are complete.";
else
    value = "No final Conservative/Balanced/Aggressive flight recommendation is issued. Physical screening supports Level 1–2 for subsequent controlled Native AutoTune work and Level 3 only as a matched engineering candidate, but repeatability/official-completion evidence is incomplete.";
end
end

function value = numberOrBlank(x)
if isfinite(double(x)), value=sprintf("%.4g",double(x)); else, value=""; end
end

function value = statsNumber(x)
if isfinite(double(x)), value=sprintf("%.6g",double(x)); else, value="N/A"; end
end

function value = blankNone(x)
value=string(x);
if ismissing(value) || strlength(value)==0, value="NONE"; end
end

function value = passText(condition)
if logical(condition), value="PASS"; else, value="FAIL"; end
end

function value = ternary(condition,a,b)
if condition, value=a; else, value=b; end
end
