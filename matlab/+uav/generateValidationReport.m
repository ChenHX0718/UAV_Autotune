function value = tableHeader(columns)
value = ["| "+join(columns," | ")+" |"; ...
    "|"+join(repmat("---",size(columns)),"|")+"|"];
end

function lines = sourceRows(T)
lines = strings(height(T),1);
for k=1:height(T)
    lines(k)=sprintf("| %s | %s | %+.0f | %.2f | %.2f | %.0f |", ...
        T.Surface(k),T.DataSource(k),T.Direction(k),T.MinDeflection_deg(k), ...
        T.MaxDeflection_deg(k),T.NeutralPWM_us(k));
end
end

function lines = directionRows(T)
lines = strings(height(T),1);
for k=1:height(T)
    lines(k)=sprintf("| %s | %+.0f | %.0f / %.0f / %.0f / %.0f | %.2f / %.2f / %.2f / %.2f | %.5f / %.5f / %.5f | %s |", ...
        T.Axis(k),T.CommandDirection(k),T.PWM_L_us(k),T.PWM_R_us(k), ...
        T.PWM_E_us(k),T.PWM_Rudder_us(k),T.AileronLeft_deg(k), ...
        T.AileronRight_deg(k),T.Elevator_deg(k),T.Rudder_deg(k), ...
        T.Cl(k),T.Cm(k),T.Cn(k),passText(T.Pass(k)));
end
end

function lines = rollRows(T)
lines = strings(height(T),1);
