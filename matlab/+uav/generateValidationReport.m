function lines = overshootRows(T)
lines = strings(height(T),1);
for k=1:height(T)
    lines(k)=sprintf("| %s | %.2f | %.2f | %s |",T.Case(k), ...
        T.ExpectedPercent(k),T.OvershootPercent(k),passText(T.Pass(k)));
