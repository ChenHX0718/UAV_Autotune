    lines(k)=sprintf("| %.0f | %s | %.3f | %.2f | %.2f | %s |", ...
        T.Airspeed_mps(k),T.Direction(k),T.T90_s(k),T.p_avg_90_deg_s(k), ...
        T.p_op_max_deg_s(k),T.Limit(k));
