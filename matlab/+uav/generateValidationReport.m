end

function [root,status,runs] = latestRepeatability(base)
parent = fullfile(base,"autotune_repeatability");
items = dir(parent); items = items([items.isdir]);
items = items(~ismember({items.name},{'.','..','roll','pitch'}));
[~,order] = sort([items.datenum],"descend");
root = ""; status = "NOT_COMPLETE"; runs = table;
for idx = order
    candidate = fullfile(items(idx).folder,items(idx).name);
    if isfile(fullfile(candidate,"INVALIDATED.json")), continue; end
    summaryFile = fullfile(candidate,"repeatability_summary.json");
    runsFile = fullfile(candidate,"repeatability_runs_all_axes.csv");
    root = string(candidate);
    if isfile(runsFile)
        runs = readtable(runsFile,"Delimiter",",","TextType","string");
    end
    if isfile(summaryFile)
        value = jsondecode(fileread(summaryFile)); status = string(value.status);
    else
        status = "RUNNING_OR_INCOMPLETE";
    end
    return
end
end

function lines = repeatabilityRows(T)
if isempty(T)
    lines = "No complete non-invalidated repeatability summary is available."; return
end
lines = [tableHeader(["Axis","Trial","Status","Completion","Finished s","Failure"]); strings(height(T),1)];
for k=1:height(T)
    lines(k+2)=sprintf("| %s | %.0f | %s | %s | %s | %s |", ...
        T.Axis(k),T.Trial(k),T.Status(k),T.CompletionClass(k), ...
        numberOrBlank(T.FirstFinishedTime_s(k)),blankNone(T.FailureReason(k)));
end
end

function [rollStats,pitchStats] = repeatabilityStats(root)
rollStats = table;
pitchStats = table;
if strlength(root) == 0, return; end
rollFile = fullfile(root,"roll","repeatability_statistics.csv");
pitchFile = fullfile(root,"pitch","repeatability_statistics.csv");
if isfile(rollFile)
    rollStats = readtable(rollFile,"Delimiter",",","TextType","string");
end
if isfile(pitchFile)
    pitchStats = readtable(pitchFile,"Delimiter",",","TextType","string");
end
end

function lines = statisticsRows(T)
if isempty(T)
    lines = "No parameter statistics are available.";
    return
end
lines = [tableHeader(["Parameter","N","Mean","Std","CV","Minimum","Maximum","Pass"]); ...
    strings(height(T),1)];
for k=1:height(T)
    lines(k+2)=sprintf("| %s | %.0f | %s | %s | %s | %s | %s | %s |", ...
        T.Parameter(k),T.N(k),statsNumber(T.Mean(k)),statsNumber(T.Std(k)), ...
        statsNumber(T.CV(k)),statsNumber(T.Minimum(k)), ...
        statsNumber(T.Maximum(k)),passText(T.Pass(k)));
end
end

function value = officialCount(T,axisName)
if isempty(T)
    value = 0;
else
    value = nnz(T.Axis == axisName & ...
        T.CompletionClass == "COMPLETE_OFFICIAL_FINISHED" & T.Status == "PASS");
end
end

